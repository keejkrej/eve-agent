import { mkdir, readFile, rename, rm, writeFile } from "node:fs/promises";
import path from "node:path";
import os from "node:os";
import { spawn } from "node:child_process";
import { randomUUID } from "node:crypto";

interface PluginRecord {
  namespace: string;
  packageName: string;
  source: string;
  dependencies?: string[];
  externalDependencies?: string[];
}
interface PluginState { version: 1; plugins: PluginRecord[] }

const statePath = (appRoot: string) => path.join(appRoot, ".eve-agent", "plugins.json");

async function readState(appRoot: string): Promise<PluginState> {
  try {
    const parsed = JSON.parse(await readFile(statePath(appRoot), "utf8")) as PluginState;
    return { version: 1, plugins: Array.isArray(parsed.plugins) ? parsed.plugins : [] };
  } catch (error) {
    if ((error as NodeJS.ErrnoException).code !== "ENOENT") throw error;
    return { version: 1, plugins: [] };
  }
}

async function writeState(appRoot: string, state: PluginState): Promise<void> {
  const file = statePath(appRoot);
  await mkdir(path.dirname(file), { recursive: true });
  const temporary = `${file}.${randomUUID()}.tmp`;
  await writeFile(temporary, `${JSON.stringify(state, null, 2)}
`, "utf8");
  await rename(temporary, file);
}

async function writePluginSettings(appRoot: string, state: PluginState): Promise<void> {
  const dependencies = [...new Set(state.plugins.flatMap((plugin) => plugin.externalDependencies ?? []))].sort();
  const file = path.join(appRoot, "agent", "lib", "plugin-settings.ts");
  await mkdir(path.dirname(file), { recursive: true });
  await writeFile(
    file,
    `// Generated by eve-agent plugin commands.
export const pluginExternalDependencies = ${JSON.stringify(dependencies, null, 2)} as const;
`,
    "utf8",
  );
}

function run(command: string, args: string[], cwd: string): Promise<void> {
  return new Promise((resolve, reject) => {
    const child = spawn(command, args, { cwd, env: process.env, stdio: "inherit" });
    child.on("error", reject);
    child.on("exit", (code) => code === 0 ? resolve() : reject(new Error(`${command} exited with status ${code ?? "unknown"}`)));
  });
}

function localSource(source: string): string | undefined {
  if (source.startsWith("~")) return path.resolve(os.homedir(), source.slice(2));
  if (source.startsWith(".") || path.isAbsolute(source)) return path.resolve(source);
}

async function packageInfoFor(source: string): Promise<{
  packageName: string;
  localDependencies: string[];
  externalDependencies: string[];
  localRoot?: string;
}> {
  const local = localSource(source);
  if (local) {
    const manifest = JSON.parse(await readFile(path.join(local, "package.json"), "utf8")) as {
      name?: unknown;
      eveAgent?: { localDependencies?: unknown; externalDependencies?: unknown };
    };
    if (typeof manifest.name !== "string" || !manifest.name) throw new Error(`Plugin package has no name: ${local}`);
    const declared = manifest.eveAgent?.localDependencies;
    const localDependencies = Array.isArray(declared)
      ? declared.filter((value): value is string => typeof value === "string").map((value) => path.resolve(local, value))
      : [];
    const external = manifest.eveAgent?.externalDependencies;
    const externalDependencies = Array.isArray(external)
      ? external.filter((value): value is string => typeof value === "string")
      : [];
    return { packageName: manifest.name, localDependencies, externalDependencies, localRoot: local };
  }
  const withoutProtocol = source.startsWith("npm:") ? source.slice(4) : source;
  const packageName = withoutProtocol.startsWith("@")
    ? withoutProtocol.split("@").slice(0, 2).join("@")
    : withoutProtocol.split("@")[0] || withoutProtocol;
  return { packageName, localDependencies: [], externalDependencies: [] };
}

function defaultNamespace(packageName: string): string {
  if (packageName.includes("prime-agent")) return "prime";
  const base = packageName.split("/").at(-1) ?? packageName;
  return base.replace(/(?:^eve-|\-eve$|\-extension$)/g, "").replace(/[^a-zA-Z0-9_-]+/g, "-") || "plugin";
}

function validateNamespace(value: string): string {
  if (!/^[a-z][a-z0-9_-]*$/i.test(value)) throw new Error("Plugin namespace must start with a letter and contain only letters, digits, _, or -");
  return value;
}

export async function installPlugin(appRoot: string, source: string, requestedNamespace?: string): Promise<PluginRecord> {
  if (!source) throw new Error("Usage: eve-agent plugin install <package-or-path> [namespace]");
  const info = await packageInfoFor(source);
  const { packageName, localDependencies, localRoot } = info;
  let { externalDependencies } = info;
  const namespace = validateNamespace(requestedNamespace || defaultNamespace(packageName));
  const state = await readState(appRoot);
  const collision = state.plugins.find((entry) => entry.namespace === namespace || entry.packageName === packageName);
  if (collision) throw new Error(`Plugin already installed as ${collision.namespace}: ${collision.packageName}`);
  if (localRoot) {
    for (const dependency of localDependencies) {
      await run("npm", ["run", "build", "--if-present", "--prefix", dependency], appRoot);
    }
    await run("npm", ["run", "build", "--if-present", "--prefix", localRoot], appRoot);
  }
  await run("npm", ["install", "--save-exact", source], appRoot);
  if (!localRoot) {
    const installed = JSON.parse(await readFile(path.join(appRoot, "node_modules", packageName, "package.json"), "utf8")) as {
      eveAgent?: { externalDependencies?: unknown };
    };
    const declared = installed.eveAgent?.externalDependencies;
    externalDependencies = Array.isArray(declared)
      ? declared.filter((value): value is string => typeof value === "string")
      : [];
  }
  const dependencyPackages: string[] = [];
  for (const dependency of localDependencies) {
    const manifest = JSON.parse(await readFile(path.join(dependency, "package.json"), "utf8")) as { name?: unknown };
    if (typeof manifest.name !== "string" || !manifest.name) throw new Error(`Local plugin dependency has no name: ${dependency}`);
    await run("npm", ["install", "--save-exact", dependency], appRoot);
    dependencyPackages.push(manifest.name);
  }
  const mountDir = path.join(appRoot, "agent", "extensions");
  await mkdir(mountDir, { recursive: true });
  await writeFile(
    path.join(mountDir, `${namespace}.ts`),
    `// Managed by eve-agent plugin install.
export { default } from ${JSON.stringify(packageName)};
`,
    "utf8",
  );
  const record = {
    namespace,
    packageName,
    source,
    ...(dependencyPackages.length ? { dependencies: dependencyPackages } : {}),
    ...(externalDependencies.length ? { externalDependencies } : {}),
  };
  state.plugins.push(record);
  state.plugins.sort((a, b) => a.namespace.localeCompare(b.namespace));
  await writeState(appRoot, state);
  await writePluginSettings(appRoot, state);
  return record;
}

export async function removePlugin(appRoot: string, selector: string): Promise<PluginRecord> {
  const state = await readState(appRoot);
  const record = state.plugins.find((entry) => entry.namespace === selector || entry.packageName === selector);
  if (!record) throw new Error(`Plugin is not installed: ${selector}`);
  await run("npm", ["uninstall", record.packageName, ...(record.dependencies ?? [])], appRoot);
  await rm(path.join(appRoot, "agent", "extensions", `${record.namespace}.ts`), { force: true });
  state.plugins = state.plugins.filter((entry) => entry !== record);
  await writeState(appRoot, state);
  await writePluginSettings(appRoot, state);
  return record;
}

export async function listPlugins(appRoot: string): Promise<PluginRecord[]> {
  return (await readState(appRoot)).plugins;
}
