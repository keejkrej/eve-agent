import { mkdir, rename, writeFile } from "node:fs/promises";
import { randomUUID } from "node:crypto";
import path from "node:path";

export async function writeActiveSettingsFile(appRoot, config) {
  const settings = {
    model: config.model ?? "gateway",
    reasoning: config.reasoning ?? "high",
    priority: config.priority === true,
  };
  const file = path.join(appRoot, "agent", "lib", "active-settings.generated.ts");
  await mkdir(path.dirname(file), { recursive: true });
  const source = `// Generated by eve-agent. Do not edit.\nexport const activeSettings = ${JSON.stringify(settings, null, 2)} as const;\n`;
  const temporary = `${file}.${randomUUID()}.tmp`;
  await writeFile(temporary, source, "utf8");
  await rename(temporary, file);
  const reloadRuntime = globalThis[Symbol.for("eve-agent/settings-changed")];
  if (typeof reloadRuntime === "function") await reloadRuntime(settings);
  return settings;
}
